#!/usr/bin/env python3
"""Export the GA speed table for the robot (amr_navigation smart_speed_node.py):
payload grid -> (accel, vmax) per objective, from ga_speed_profile.py with the poly2 surrogate.
  tested: snapped to a tested profile (a0.15 v0.30 / v0.40 ...)  <- default on the robot
  ga:     continuous GA optimum, 0.01 resolution (untested speeds)
Output: models/ga_speed_table.yaml"""
import os, sys, json, subprocess, numpy as np, yaml
ROOT = os.path.dirname(os.path.abspath(__file__))
GRID = [float(x) for x in np.arange(0, 26.0 + 1e-9, 1.0)] + [25.77]
def run(kg, obj, snap):
    cmd = [sys.executable, os.path.join(ROOT, 'ga_speed_profile.py'), '--payload', str(kg), '--objective', obj,
           '--i-peak-max', '10.42', '--surrogate', 'poly'] + ([] if snap else ['--no-snap'])
    s = subprocess.check_output(cmd, stderr=subprocess.DEVNULL).decode(); o = json.loads(s[s.index('{'):])
    return dict(payload_kg=round(kg, 2), accel=float(o['accel']), vmax=float(o['vmax']))
out = dict(source='ml/export_ga_table.py (ga_speed_profile.py, poly2 surrogate, i_peak_max 10.42 A)',
           weighing_profile=dict(accel=0.15, vmax=0.20),
           note='lookup: first row with payload_kg >= estimate+margin; above the last row keep the weighing profile',
           tables={})
for obj in ('battery', 'motor'):
    for mode, snap in (('tested', True), ('ga', False)):
        rows = sorted({r['payload_kg']: r for r in (run(kg, obj, snap) for kg in sorted(set(GRID)))}.values(), key=lambda r: r['payload_kg'])
        out['tables'][f'{obj}_{mode}'] = rows
        print(obj, mode, [(r['payload_kg'], r['vmax']) for r in rows][::5])
with open(os.path.join(ROOT, 'models', 'ga_speed_table.yaml'), 'w') as f:
    f.write('# generated by ml/export_ga_table.py - do not edit by hand\n'); yaml.safe_dump(out, f, sort_keys=False)
