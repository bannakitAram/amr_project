#!/usr/bin/env python3
"""Early payload estimate: Linear regression on I_med + Ib_cru (cumulative from motion start).
For every evaluation time t (s after motion start) a separate linear model is cross-validated;
the EARLIEST t whose error meets the target (P95 |err| in BOTH CVs) and keeps meeting it
for --stable seconds is chosen and exported to
models/weight_linear.yaml (coefficients + t_eval + margin) for the online node / GA."""
import os, argparse, json, numpy as np, pandas as pd
from sklearn.linear_model import LinearRegression
import train_weight_mlp as W

ROOT = os.path.dirname(os.path.abspath(__file__))
IDX = [1, 2]; FEATS = [W.FEATS[i] for i in IDX]          # I_med, Ib_cru

def cv_err(runs, X, y, key):
    e = np.full(len(y), np.nan)
    for v in runs[key].unique():
        t = (runs[key] == v).values
        e[t] = LinearRegression().fit(X[~t], y[~t]).predict(X[t]) - y[t]
    return e

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--p95-max', type=float, default=2.5, help='target P95 |error| [kg]')
    ap.add_argument('--t-min', type=float, default=5); ap.add_argument('--t-max', type=float, default=60)
    ap.add_argument('--step', type=float, default=1)
    ap.add_argument('--stable', type=float, default=5, help='target must also hold for the next N seconds')
    a = ap.parse_args()
    runs = pd.read_csv(os.path.join(ROOT, 'data', 'runs.csv'))
    runs = runs[runs.profile == W.PROFILE].reset_index(drop=True)
    ts = [dict(np.load(os.path.join(ROOT, 'data', 'ts', b + '.npz'))) for b in runs.bag]
    y = runs.payload_kg.values
    rows, best, Xs = [], None, {}
    for t in np.arange(a.t_min, a.t_max + 1e-9, a.step):
        F = [W.cumulative_features(d, t) for d in ts]
        if any(f is None for f in F): continue                  # not every bag has cruise data yet
        X = np.array(F)[:, IDX]
        r = dict(t=t)
        for key, n in (('run', 'lorun'), ('payload_kg', 'lopay')):
            e = np.abs(cv_err(runs, X, y, key))
            r[n + '_mae'], r[n + '_p95'], r[n + '_max'] = e.mean(), np.percentile(e, 95), e.max()
        rows.append(r); Xs[t] = X
    tab = pd.DataFrame(rows)
    tab['worst_p95'] = tab[['lorun_p95', 'lopay_p95']].max(axis=1)
    ok = tab.worst_p95 <= a.p95_max
    for i, t in enumerate(tab.t):      # earliest t that passes and keeps passing for --stable s
        win = (tab.t >= t) & (tab.t <= t + a.stable)
        if tab.t.iloc[-1] >= t + a.stable and ok[win].all():
            r = tab.iloc[i].to_dict(); r['worst_p95'] = float(tab.worst_p95[win].max())
            best = (t, Xs[t], r); break
    tab = tab.round(2)
    print(tab.to_string(index=False))
    if best is None:
        raise SystemExit(f'no t in [{a.t_min},{a.t_max}] s reaches P95 <= {a.p95_max} kg')
    t, X, r = best
    lr = LinearRegression().fit(X, y)
    margin = float(round(r['worst_p95'], 2))   # worst P95 over the stable window
    out = dict(profile=W.PROFILE, t_eval_s=float(t), features=FEATS,
               intercept=float(lr.intercept_), coef={f: float(c) for f, c in zip(FEATS, lr.coef_)},
               margin_kg=margin, payload_range_kg=[float(y.min()), float(y.max())],
               cv={k: round(float(v), 3) for k, v in r.items() if k != 't'},
               feature_def={'I_med': 'median(|I_L|+|I_R|) while v>0.03, from motion start to t_eval',
                            'Ib_cru': 'median(battery current) while |a|<0.02, v>0.15, |w|<0.1, same window'},
               selection=f'earliest t with P95 |err| <= {a.p95_max} kg in both CVs, holding for the next {a.stable:g} s')
    with open(os.path.join(ROOT, 'models', 'weight_linear.yaml'), 'w') as f:
        f.write('# generated by train_weight_linear.py\n')
        import yaml; yaml.safe_dump(out, f, sort_keys=False)
    tab.to_csv(os.path.join(ROOT, 'models', 'weight_linear_vs_time.csv'), index=False)
    print(f'\nchosen t_eval = {t:.0f} s  ->  payload = {lr.intercept_:.2f} '
          + ' '.join(f'{c:+.2f}*{f}' for f, c in zip(FEATS, lr.coef_)) + f'   (margin {margin} kg)')

if __name__ == '__main__':
    main()
